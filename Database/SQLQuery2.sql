USE [QuanLyBanDienThoai];

SELECT Bang, SoDong,
       CASE WHEN SoDong < 20 THEN 20 - SoDong ELSE 0 END AS CanThem
FROM (
    SELECT N'Loại điện thoại' AS Bang, COUNT(*) AS SoDong FROM dbo.LOAIDIENTHOAI
    UNION ALL SELECT N'Hãng điện thoại', COUNT(*) FROM dbo.HANGDT
    UNION ALL SELECT N'Nhà cung cấp', COUNT(*) FROM dbo.NHACUNGCAP
    UNION ALL SELECT N'Điện thoại', COUNT(*) FROM dbo.DIENTHOAI
    UNION ALL SELECT N'Nhân viên', COUNT(*) FROM dbo.NHANVIEN
    UNION ALL SELECT N'Khách hàng', COUNT(*) FROM dbo.KHACHHANG
    UNION ALL SELECT N'Tài khoản', COUNT(*) FROM dbo.TAIKHOAN
    UNION ALL SELECT N'Giỏ hàng', COUNT(*) FROM dbo.GIOHANG
    UNION ALL SELECT N'Khuyến mãi', COUNT(*) FROM dbo.KHUYENMAI
    UNION ALL SELECT N'Chi tiết khuyến mãi', COUNT(*) FROM dbo.CHITIETKHUYENMAI
    UNION ALL SELECT N'Phiếu nhập', COUNT(*) FROM dbo.PHIEUNHAPHANG
    UNION ALL SELECT N'Chi tiết phiếu nhập', COUNT(*) FROM dbo.CHITIETPHIEUNHAPHANG
    UNION ALL SELECT N'Hóa đơn', COUNT(*) FROM dbo.HOADON
    UNION ALL SELECT N'Chi tiết hóa đơn', COUNT(*) FROM dbo.CHITIETHOADON
    UNION ALL SELECT N'Bảo hành', COUNT(*) FROM dbo.BAOHANH
) AS KiemTra
ORDER BY CanThem DESC, Bang;